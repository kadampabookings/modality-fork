package one.modality.crm.server.authn.gateway.shared;

/**
 * Why a booking cart carries no guest link — the answers that used to arrive as one message.
 *
 * <p>{@code /cart/:uuid} opens a guest session from the cart's BOOKING_ACCESS link, and
 * {@link GuestBookingAccess} decides from the database whether a cart may carry one. When it may not, the
 * cart page's sign-in fails — and every one of those failures said the same thing, "No magic link
 * associated with cart #N", at ERROR. A cost followed on each side of the wire. In the log, the ordinary
 * case (the booker has an account and is meant to sign in) is indistinguishable from a guest who is
 * genuinely stuck, so the line reads as a fault every day and nobody can tell how much of it is one;
 * placing it took a staging query and three census runs. In the browser the page could only guess, so it
 * told everyone "This booking is linked to your account" — true for the great majority, and an invention
 * for the person whose booking carries no address at all.
 *
 * <p>Measured on staging (an anonymised production copy) on 2026-11-04, over all 240,780 carts that have
 * bookings: 72.37% {@link #ACCOUNT_REQUIRED}, 1.92% {@link #NO_BOOKING_EMAIL}, 0.63%
 * {@link #MIXED_BOOKING_EMAILS}, 25.07% eligible for a link. {@link #EMAIL_TOO_LONG} reads 0 there, but
 * staging rewrites addresses, so that bucket cannot be measured on it. Of the carts refused for
 * ACCOUNT_REQUIRED, 2 are also billed to a payer and NONE is billed to a payer without having an account
 * — which is why those two conditions share one answer rather than getting a screen each.
 *
 * <p>The key in brackets is what the front office matches ({@code hasServerErrorKey} in the React client),
 * the same shape {@code ModalityPasswordAuthenticationGateway} uses for its own refusals. It is
 * deliberately NOT a {@code ModalityAuthenticationI18nKeys} entry: that interface is generated by WebFX
 * from the i18n dictionaries so JAVA clients can translate a key, and no Java client calls this endpoint —
 * the cart page is React and translates these in its own catalogue. Adding one there would mean editing a
 * WebFX-managed file and running {@code webfx update} across the repo for a string nothing would read.
 *
 * <p>What a reason may say is bounded by who can ask. The caller holds the cart uuid, which is the
 * bearer token of that cart: whoever has it can already list the cart's bookings through the page's own
 * unfiltered probe and pay them at /pay-cart. So a reason discloses a property of a booking the asker can
 * already see — never a value: no address, no name, and nothing about any OTHER cart. ACCOUNT_REQUIRED in
 * particular tells the holder nothing the current screen does not already say out loud.
 */
public enum GuestLinkRefusal {

    /** No cart carries that uuid — a mistyped, truncated or made-up link. */
    UNKNOWN_CART("CartLinkUnknownCartError", "no cart carries that uuid"),

    /** The cart exists but holds no booking; nothing to open, and nobody to open it for. */
    NO_BOOKINGS("CartLinkNoBookingsError", "it holds no booking"),

    /**
     * The booker signs in instead: a booking's person has a front-office account, or the booking is billed
     * to a payer (a payer's cart holds the bookings of everyone they pay for, so it has no single guest
     * identity to open as). The deliberate case, and nearly all of them.
     */
    ACCOUNT_REQUIRED("CartLinkAccountRequiredError", "its booker signs in (account, or billed to a payer)"),

    /** A booking in the cart carries no email address, so there is nothing to mint a link for. */
    NO_BOOKING_EMAIL("CartLinkNoBookingEmailError", "a booking carries no email address"),

    /**
     * The cart's bookings carry more than one address. A cart carries ONE guest identity, so a link here
     * would open one person's booking to the other.
     */
    MIXED_BOOKING_EMAILS("CartLinkMixedEmailsError", "its bookings carry more than one address"),

    /** The address does not fit {@code magic_link.email}, so a link could not be stored for it. */
    EMAIL_TOO_LONG("CartLinkEmailTooLongError", "its address does not fit magic_link.email");

    private final String errorKey;
    private final String reason;

    GuestLinkRefusal(String errorKey, String reason) {
        this.errorKey = errorKey;
        this.reason = reason;
    }

    /** The token the front office matches, between brackets in the failure message. */
    public String getErrorKey() {
        return errorKey;
    }

    /**
     * The failure a cart page sign-in is refused with: the key the client matches, then what the log needs
     * to be read without a database. The cart's internal id, as the message has always carried — never its
     * uuid, which is the credential (see {@code f16b3d0d1}).
     */
    public String failureMessage(Object cartPk) {
        return "[" + errorKey + "] "
               + (cartPk == null ? "No guest link" : "No guest link for cart #" + cartPk)
               + ": " + reason;
    }
}
