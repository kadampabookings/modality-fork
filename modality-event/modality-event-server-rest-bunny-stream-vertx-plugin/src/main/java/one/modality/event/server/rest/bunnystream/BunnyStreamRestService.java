    /** Build a flat user-facing message from the structured missing-field codes —
     *  used for {@code /init}, {@code /status}, {@code /abort} which return text
     *  errors. {@code /library} returns the structured list directly. */
    private static String missingMessage(List<String> missing) {
        if (missing.contains(MISSING_API_KEY)) return "Bunny API key missing on the organization (set Organization.bunnyApiKey).";
        if (missing.contains(MISSING_LIBRARY)) return "Bunny library ID missing on the event (set Event.vodBunnyLibraryId).";
        if (missing.contains(MISSING_PULL_ZONE)) return "Bunny pull zone ID missing on the event (set Event.vodBunnyPullZoneId).";
        return "Bunny credentials are not configured.";
    }

