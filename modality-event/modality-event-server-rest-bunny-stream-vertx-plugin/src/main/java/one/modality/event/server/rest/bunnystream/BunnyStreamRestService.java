    // ─── /rest/videos/library-info ─────────────────────────────────────────

    /**
     * Drives the stats banner and the missing-credentials empty state on the React
     * Library Management tab. Always returns {@code 200 OK} — the React layer reads
     * {@code ok}/{@code missingFields}/{@code error} to drive its UI, mirroring the
     * {@link #handleLibrary} contract.
     *
     * <p>The Bunny library JSON exposes {@code Name}, {@code StorageUsage} (bytes),
     * {@code TrafficUsage} (bytes), and {@code VideoCount} — enough for the four-tile
     * stats banner; we don't need the heavier {@code /statistics} time series for v1.
     */
    private void handleLibraryInfo(RoutingContext ctx) {
        Long eventId = parseLong(ctx.request().getParam("eventId"));
        if (eventId == null) {
            sendError(ctx, BAD_REQUEST_400, "missing eventId");
            return;
        }
        loadCredentialsByEventId(eventId).onComplete(ar -> {
            if (ar.failed()) {
                sendError(ctx, INTERNAL_SERVER_ERROR_500, ar.cause().getMessage());
                return;
            }
            BunnyCredentials creds = ar.result();
            List<String> missing = creds.missingFields();
            if (!missing.isEmpty()) {
                sendJson(ctx, OK_200, jsonLibraryMissing(missing));
                return;
            }
            // The account-level API at api.bunny.net returns Name + the usage
            // counters (StorageUsage / TrafficUsage / VideoCount); the Stream API
            // at video.bunnycdn.com returns only library settings, so those counters
            // come back as zero from there. We try the account API first and fall
            // back to the Stream API (with the resolved per-library key) when the
            // user-supplied key is itself a per-library Stream key — Bunny signals
            // that with either HTTP 401 OR an HTTP 200 + {ErrorKey, Message} body.
            BunnyStreamApiClient.getVideoLibrary(creds.libraryId, creds.apiKey)
                    .compose(json -> {
                        String errorKey = json.getString("ErrorKey");
                        if (errorKey != null && !errorKey.isEmpty()) {
                            String message = json.getString("Message");
                            return Future.failedFuture("Bunny account API rejected key (" + errorKey
                                    + (message == null ? "" : ": " + message)
                                    + "). Use the account-level API key on Organization.bunnyApiKey.");
                        }
                        return Future.succeededFuture(json);
                    })
                    .recover(err -> {
                        Console.log("[BUNNY-STREAM] account API getVideoLibrary unavailable ("
                                + err.getMessage() + "); falling back to Stream API getLibrary");
                        return BunnyStreamApiClient.getLibrary(creds.libraryId, creds.streamApiKey);
                    })
                    .onSuccess(json -> {
                        String name = json.getString("Name");
                        if (isBlank(name)) name = json.getString("name");
                        long storageBytes   = Numbers.longValue(json.get("StorageUsage"));
                        long bandwidthBytes = Numbers.longValue(json.get("TrafficUsage"));
                        int videoCount      = Numbers.intValue(json.get("VideoCount"));
                        sendJson(ctx, OK_200, jsonLibraryInfoOk(
                                creds.libraryId, creds.pullZoneId, name,
                                storageBytes, bandwidthBytes, videoCount));
                    })
                    .onFailure(err -> {
                        String msg = err.getMessage();
                        Console.log("[BUNNY-STREAM] library-info both endpoints failed: " + msg);
                        sendJson(ctx, OK_200, jsonLibraryError(
                                msg == null || msg.isEmpty()
                                        ? "Bunny rejected the credentials (likely 401 Unauthorized)."
                                        : msg));
                    });
        });
    }

    // ─── /rest/videos/library-videos ───────────────────────────────────────

    /**
     * Paged list of videos in the Event's Bunny library. Pagination is preserved
     * end-to-end so the React grid can virtualise / lazy-load if the library grows
     * large; default {@code perPage=100} matches Bunny's own dashboard.
     *
     * <p>Returns {@code 400 Bad Request} when credentials are missing — the React
     * tab calls {@code library-info} first to render the missing-credentials empty
     * state, so reaching this endpoint without credentials is a programming error.
     */
    private void handleLibraryVideos(RoutingContext ctx) {
        Long eventId = parseLong(ctx.request().getParam("eventId"));
        if (eventId == null) {
            sendError(ctx, BAD_REQUEST_400, "missing eventId");
            return;
        }
        int page = clampPositive(parseInt(ctx.request().getParam("page")), 1);
        int perPage = clampRange(parseInt(ctx.request().getParam("perPage")),
                DEFAULT_VIDEOS_PER_PAGE, 1, MAX_VIDEOS_PER_PAGE);
        loadCredentialsByEventId(eventId).compose(creds -> {
            if (!creds.isComplete()) {
                return Future.failedFuture(missingMessage(creds.missingFields()));
            }
            return BunnyStreamApiClient.listVideos(creds.libraryId, creds.streamApiKey, page, perPage)
                    .map(BunnyStreamRestService::jsonLibraryVideosResponse);
        })
        .onSuccess(body -> sendJson(ctx, OK_200, body))
        .onFailure(err -> sendError(ctx, INTERNAL_SERVER_ERROR_500, err.getMessage()));
    }

